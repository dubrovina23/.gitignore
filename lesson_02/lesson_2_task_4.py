def fizz_buzz(n):
    # Перебираем числа от 1 до n включительно
    for i in range(1, n + 1):
        # 1. Сначала проверяем самое строгое условие (деление на 3 И на 5)
        if i % 3 == 0 and i % 5 == 0:
            print("FizzBuzz")
        # 2. Если не подошло, проверяем деление только на 3
        elif i % 3 == 0:
            print("Fizz")
        # 3. Если не подошло, проверяем деление только на 5
        elif i % 5 == 0:
            print("Buzz")
        # 4. Если число не делится ни на 3, ни на 5, печатаем само число
        else:
            print(i)


fizz_buzz(17)
